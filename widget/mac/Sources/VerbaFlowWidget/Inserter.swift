import AppKit

/// Puts the accepted text into the program as a paste of plain text, which every Mac program understands and which
/// takes the formatting of the place it lands. The clipboard is put back as it was straight after, and the Widget's
/// text is marked as passing through so that clipboard managers do not keep it.
enum Inserter {
    /// False when the program has gone (quit) or the Widget may not press keys for it.
    @MainActor
    static func paste(_ text: String, into target: FocusTarget) async -> Bool {
        guard !target.app.isTerminated, FocusTarget.trusted else { return false }
        let board = NSPasteboard.general
        let saved = save(board)
        board.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // The markers clipboard managers look for (nspasteboard.org): passing through, and not to be shown.
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        board.writeObjects([item])

        target.app.activate(options: [])
        try? await Task.sleep(nanoseconds: 200_000_000) // the program comes to the front and puts its cursor back
        Keys.paste()
        // The program reads the clipboard when it handles the paste; slow programs get a second before it is put back.
        try? await Task.sleep(nanoseconds: 1_000_000_000)
        restore(saved, board)
        return true
    }

    /// Takes out the selected text (Accept with an emptied box after selecting text).
    @MainActor
    static func deleteSelection(in target: FocusTarget) async -> Bool {
        guard !target.app.isTerminated, FocusTarget.trusted else { return false }
        target.app.activate(options: [])
        try? await Task.sleep(nanoseconds: 200_000_000)
        Keys.delete()
        return true
    }

    /// The text copied for the person to paste themselves.
    static func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    /// Everything on the clipboard, every form of it, to put back after the paste.
    private static func save(_ board: NSPasteboard) -> [NSPasteboardItem] {
        (board.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types { if let d = item.data(forType: type) { copy.setData(d, forType: type) } }
            return copy
        }
    }

    private static func restore(_ saved: [NSPasteboardItem], _ board: NSPasteboard) {
        board.clearContents()
        if !saved.isEmpty { board.writeObjects(saved) }
    }
}
